h2('2.2 为什么必须使用 Global 模式')
para('分流模式（Simple）下，仅被规则匹配的流量走代理，其余流量直连。爬虫在请求目标站点时会出现“代理出口 IP 与国内直连 IP”混合出现的特征；同时网站能观察到访问者的真实出口位置（中国 IP），既容易被风控系统判定为异常流量，也会让数据在地域代表性上失真。')
para('全局模式（Global）保证爬虫的所有流量出口一致且稳定为国外 IP，是外网爬取的基础前提，也是本项目“阶段0 环境准备”的首要验收项。', bold=True)

