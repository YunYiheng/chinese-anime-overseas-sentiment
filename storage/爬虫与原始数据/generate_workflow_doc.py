from docx.oxml.ns import qn

EAST_ASIAN_FONT = '微软雅黑'

doc = Document()

# ---------- 全局样式 ----------
def set_run_font(run, size=10.5, bold=False, color=None, name='Calibri'):
    run.font.name = name
    run.font.size = Pt(size)
    run.font.bold = bold
    if color is not None:
        run.font.color.rgb = color
    rPr = run._element.get_or_add_rPr()
    rFonts = rPr.get_or_add_rFonts()
    rFonts.set(qn('w:eastAsia'), EAST_ASIAN_FONT)

normal = doc.styles['Normal']
normal.font.name = 'Calibri'
normal.font.size = Pt(10.5)
normal.element.rPr.rFonts.set(qn('w:eastAsia'), EAST_ASIAN_FONT)

for hname, hsize in [('Heading 1', 16), ('Heading 2', 13.5), ('Heading 3', 11.5)]:
    st = doc.styles[hname]
    st.font.name = 'Calibri'
    st.font.size = Pt(hsize)
    st.font.color.rgb = RGBColor(0x1F, 0x3B, 0x57)
    st.font.bold = True
    st.element.rPr.rFonts.set(qn('w:eastAsia'), EAST_ASIAN_FONT)

# ---------- 工具函数 ----------
def para(text, size=10.5, bold=False, italic=False, color=None, align=None):
    p = doc.add_paragraph()
    r = p.add_run(text)
    set_run_font(r, size=size, bold=bold, color=color)
    r.font.italic = italic
    if align == 'center':
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    return p

def bullet(text, bold_prefix=None, level=0):
    p = doc.add_paragraph(style='List Bullet')
    if bold_prefix:
        r = p.add_run(bold_prefix)
        set_run_font(r, bold=True)
        r2 = p.add_run(text)
        set_run_font(r2)
    else:
        r = p.add_run(text)
        set_run_font(r)
    return p

def numbered(text, bold_prefix=None):
    p = doc.add_paragraph(style='List Number')
    if bold_prefix:
        r = p.add_run(bold_prefix)
        set_run_font(r, bold=True)
        r2 = p.add_run(text)
        set_run_font(r2)
    else:
        r = p.add_run(text)
        set_run_font(r)
    return p

def h1(text):
    doc.add_heading(text, level=1)

def h2(text):
    doc.add_heading(text, level=2)

def h3(text):
    doc.add_heading(text, level=3)

def table(headers, rows, widths=None):
    t = doc.add_table(rows=1 + len(rows), cols=len(headers))
    t.style = 'Table Grid'
    t.autofit = True
    for j, htext in enumerate(headers):
        cell = t.cell(0, j)
        cell.paragraphs[0].text = ''
        r = cell.paragraphs[0].add_run(htext)
        set_run_font(r, bold=True)
    for i, row in enumerate(rows, start=1):
        for j, val in enumerate(row):
            cell = t.cell(i, j)
            cell.paragraphs[0].text = ''
            r = cell.paragraphs[0].add_run(str(val))
            set_run_font(r)
    if widths:
        for j, w in enumerate(widths):
            for row in t.rows:
                row.cells[j].width = Cm(w)
    doc.add_paragraph()
    return t

def page_break():
    doc.add_page_break()

def callout(text):
    p = doc.add_paragraph()
    r = p.add_run(text)
    set_run_font(r, bold=True, color=RGBColor(0xC0, 0x00, 0x00))
    return p

